def load_latest_json(prefix: str):
    """Load the latest JSON file matching the prefix from the reports directory."""
    files = glob.glob(f"reports/{prefix}_*.json")
    if not files:
        return None
    latest_file = max(files, key=os.path.getctime)
    with open(latest_file, "r") as f:
        return json.load(f)

